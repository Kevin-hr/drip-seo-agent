# Calculate epoch using these
epochs = []
for vid, dt in id_known.items():
    shifted = int(vid) >> 22
    dt_ms = int(dt.timestamp() * 1000)
    ep = shifted - dt_ms
    epochs.append(ep)
    print(f"  {vid}: shifted={shifted}, date_ms={dt_ms}, epoch={ep}")

EPOCH = sum(epochs) // len(epochs)
print(f"\nEPOCH = {EPOCH}")

def vid_to_dt_cst(vid):
    ts_ms = (int(vid) >> 22) - EPOCH
    return datetime.fromtimestamp(ts_ms/1000, tz=CST)

# Verify
